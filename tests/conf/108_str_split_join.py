# str methods: split, rsplit, join, splitlines
print("split default:", "the quick  brown   fox".split())
print("split strips ends:", "  padded words  ".split())
print("split on sep:", "a,b,c".split(","))
print("split keeps empties:", "a,,b,".split(","), ",".split(","))
print("split on one space:", "a  b".split(" "))
print("split multi-char sep:", "1 -> 2 -> 3".split(" -> "))
print("split maxsplit:", "a,b,c,d".split(",", 1), "a b c d".split(None, 2))
print("split maxsplit keyword:", "a,b,c,d".split(",", maxsplit=2))
print("split missing sep:", "abc".split(","))
print("split empty string:", "".split(), "".split(","))
print("split whitespace only:", "   ".split())
print("split tabs/newlines:", "a\tb\nc  d".split())
print("rsplit:", "a,b,c,d".rsplit(",", 1), "a,b,c,d".rsplit(","))
print("rsplit default sep:", "one two three".rsplit(None, 1))
print("rsplit path:", "dir/sub/file.txt".rsplit("/", 1), "file.tar.gz".rsplit(".", 1))
print("split to ints:", [int(x) for x in "3 1 4 1 5".split()])
first, rest = "key: some value: here".split(": ", 1)
print("split unpack:", first, "|", rest)
print("word count:", len("how many words here".split()))

print("join:", ",".join(["a", "b", "c"]), " ".join(["x"]), "".join(["p", "q"]))
print("join empty list:", repr(",".join([])))
print("join string chars:", "-".join("abc"))
print("join tuple/generator:", "+".join(("1", "2")), "".join(str(n) for n in range(5)))
print("join dict keys:", ", ".join({"k1": 1, "k2": 2}))
print("join with newline:", "\n".join(["line1", "line2"]))
print("join numbers:", ", ".join(map(str, [1, 2, 3])))
print("join multi-char sep:", " and ".join(["salt", "pepper", "oil"]))
try:
    ",".join([1, 2])
except TypeError:
    print("join of non-strings raises TypeError")

print("round trip:", "-".join("a b c".split()), " ".join("a-b-c".split("-")))
print("normalize spaces:", " ".join("  too   many    spaces ".split()))
print("reverse words:", " ".join("one two three".split()[::-1]))
print("reverse each word:", " ".join(w[::-1] for w in "abc def".split()))
print("acronym:", "".join(w[0].upper() for w in "portable network graphics".split()))
print("csv row:", [field.strip() for field in "ann , 30 ,  bogota".split(",")])
print("longest word:", max("the quick brown fox".split(), key=len))
pairs = "a=1;b=2;c=3"
print("parse pairs:", {k: int(v) for k, v in (item.split("=") for item in pairs.split(";"))})

text = "first line\nsecond line\n\nfourth line"
print("splitlines:", text.splitlines())
print("trailing newline:", "a\nb\n".splitlines(), "a\nb\n".split("\n"))
print("splitlines edge cases:", "".splitlines(), "one".splitlines())
print("splitlines crlf:", "a\r\nb".splitlines())
print("line count:", len(text.splitlines()))
for number, line in enumerate(text.splitlines(), 1):
    print(number, repr(line))
print("non-empty lines:", [ln for ln in text.splitlines() if ln])
print("words per line:", [len(ln.split()) for ln in text.splitlines()])
