# Arithmetic operators, precedence and int/float mixing
print("add:", 7 + 3)
print("sub:", 7 - 10)
print("mul:", 7 * 3)
print("true div:", 7 / 2)
print("true div exact:", 6 / 3)
print("floor div:", 7 // 2)
print("mod:", 7 % 3)
print("power:", 2 ** 10)
print("neg floor div:", -7 // 2)
print("neg mod:", -7 % 3)
print("mod neg divisor:", 7 % -3)
print("precedence:", 2 + 3 * 4)
print("parens:", (2 + 3) * 4)
print("power is right assoc:", 2 ** 3 ** 2)
print("unary minus vs power:", -2 ** 2)
print("parenthesised base:", (-2) ** 2)
print("neg exponent:", 2 ** -1)
print("mixed int/float:", 1 + 2.0)
print("float mul:", 1.5 * 4)
print("float floor div:", 7.0 // 2)
print("float mod:", 7.5 % 2)
print("unary:", -(-3), +5, - -4)
print("int float equal:", 1 == 1.0)
print("divmod:", divmod(17, 5))
print("big:", 12345678901234567890 * 98765432109876543210)
print("long expr:", (1 + 2) * (3 + 4) / 7 - 1)
print("string mul:", "ab" * 3, 3 * "ab")
print("list add:", [1] + [2, 3])
x = 5
print("polynomial:", x * x - 4 * x + 4)
print("avg:", (3 + 4 + 5) / 3)
print("percent:", 45 / 60 * 100)
print("result types:", type(7 // 2).__name__, type(7 / 7).__name__,
      type(2 ** 2).__name__, type(2 ** -2).__name__)
print("multi-line expr:", (1 +
                           2 +
                           3))
total = 1 + \
    2
print("backslash continuation:", total)
print("0.1 * 3:", 0.1 * 3)
print("bool arithmetic:", True + True, 5 * False)
print("mod sign follows divisor:", -1 % 5, 1 % -5, -1 % -5)
print("floor div floats neg:", -7.5 // 2, 7.5 // -2)
print("square root via power:", 9 ** 0.5, 16 ** 0.5)
print("shifts and bits:", 1 << 4, 256 >> 2, 6 & 3, 6 | 3, 6 ^ 3)
print("precedence unary/mul:", -3 * 2, 2 * -3, 10 - -2)
print("comparison after arithmetic:", 2 + 2 == 4, 3 * 3 > 2 ** 3)
