# float: repr of common values, special values, conversions
print("simple:", 1.0, 2.5, -0.5, 100.0, 3.14)
print("int-valued floats keep .0:", 4 / 2, 2.0 * 3, 1e3, float(7))
print("0.1 + 0.2:", 0.1 + 0.2)
print("0.1 + 0.2 == 0.3:", 0.1 + 0.2 == 0.3, abs(0.1 + 0.2 - 0.3) < 1e-9)
print("classic sums:", 0.1 + 0.7, 0.1 * 3, 1.1 + 2.2, 0.5 + 0.25)
print("division:", 1 / 3, 2 / 3, 10 / 4, 1 / 8)
print("large:", 1e15, 1e16, 123456789012345680.0, 1.5e300)
print("large int-valued:", 1e5, 1e10, 9999999999999998.0, 1e22)
print("small:", 0.001, 0.0001, 0.00001, 1.5e-7, 1e-10)
print("threshold:", 0.00012, 0.000012, 123456.789e-10)
print("sci literals:", 2e3, 2.5e-3, 1E2, 6.02e23)
print("many digits:", 3.141592653589793, 2.718281828459045, 1.23456789012345678)
print("computed large/small:", 10.0 ** 16, 10.0 ** 15, 1 / 100000, 1 / 10000)

inf = float("inf")
nan = float("nan")
print("inf:", inf, float("-inf"), -inf)
print("nan:", nan)
print("inf compare:", inf > 1e308, -inf < -1e308, inf == inf)
print("inf arithmetic:", inf + 1, inf * 2, -inf + 5, 1 / inf)
print("nan compare:", nan == nan, nan != nan, nan < 1, nan > 1)
print("inf - inf:", inf - inf)
print("overflow to inf:", 1e308 * 10, -1e308 * 10)

print("float from str:", float("3.5"), float("-2"), float("1e3"), float("  4.25  "), float(".5"))
print("float from int/bool:", float(3), float(True))
print("str of float:", str(2.50), str(1e16), repr(0.1))
print("int of float:", int(2.99), int(-2.99))
print("is_integer:", (3.0).is_integer(), (3.5).is_integer(), (1e20).is_integer())
x = 7.0
print("is_integer on variable:", x.is_integer(), (x / 2).is_integer())
print("floor div:", 7.5 // 2, -7.5 // 2, 7.0 // 2, 1.0 // 0.3)
print("modulo:", 7.5 % 2, -7.5 % 2, 5.5 % -2, 0.75 % 0.5)
print("divmod:", divmod(7.5, 2), divmod(-7.5, 2))
print("power:", 2.0 ** 3, 4 ** 0.5, 2 ** -1, 1.5 ** 2)
print("mixed arithmetic:", 1 + 1.0, 3 * 0.5, 7 - 0.5)
print("comparison:", 1.0 == 1, 0.5 < 1, 2.5 >= 2.5, 1e3 == 1000)
print("abs/neg:", abs(-2.5), -(-1.5), +2.5)
print("min/max/sum:", min(1.5, 0.5), max(1.5, 2), sum([0.5, 0.25, 0.25]))
tenths = 0.0
for _ in range(10):
    tenths += 0.1
print("ten tenths added in a loop:", tenths, tenths == 1.0)
print("average:", (1 + 2 + 4) / 3)
print("percent:", 1 / 3 * 100)
print("money:", 19.99 * 3, 0.07 * 100, 1.15 * 100)
print("type:", type(1.0).__name__, type(1 / 1).__name__, isinstance(1.0, float))
print("truthiness:", bool(0.0), bool(0.1))
print("equality after ops:", 0.5 + 0.5 == 1.0, 0.1 * 3 == 0.3)
print("in containers:", [0.1, 1.0, 1e20], (2.50, -1e-7), {"pi": 3.14})
