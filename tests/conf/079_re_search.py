# re: search, match, fullmatch, findall, finditer, groups, flags, the pattern language
import re

text = "Relay 7 reported 42 faults on 2099-03-14, relay 12 reported 3."
print(re.search(r"\d+", text))
print(re.search(r"\d+", text).group())
print(re.search(r"zzz", text))
print(re.match(r"Relay", text) is not None, re.match(r"relay", text))
print(re.match(r"relay", text, re.IGNORECASE).group())
print(re.fullmatch(r"\d{4}-\d{2}-\d{2}", "2099-03-14") is not None, re.fullmatch(r"\d{4}", "2099-03"))
print(re.findall(r"\d+", text))
print(re.findall(r"[Rr]elay (\d+)", text))
print(re.findall(r"(\w+) (\d+)", text))
print(re.findall(r"x", text), re.findall(r"", "ab"))
found = re.search(r"(\d{4})-(\d{2})-(\d{2})", text)
print(found.group(0), found.group(1), found.group(2, 3), found.groups())
print(found.start(), found.end(), found.span(), found.span(2), found.start(3))
print(found[0], found[1], found.string == text, found.re.pattern, found.pos, found.lastindex)
named = re.search(r"(?P<year>\d{4})-(?P<month>\d{2})", text)
print(named.group("year"), named["month"], named.groupdict(), named.lastgroup)
print(repr(named))
optional = re.match(r"(a)(b)?(c)?", "ac")
print(optional.groups(), optional.groups("-"), optional.group(2), optional.span(2), optional.lastindex)
for hit in re.finditer(r"[A-Za-z]+", "alpha beta  gamma"):
    print(hit.group(), hit.span())
print([m.start() for m in re.finditer(r"a", "banana")])
pattern = re.compile(r"(\w)\1")
print(pattern.search("balloon").group(), pattern.findall("balloon keeper"), pattern.pattern, pattern.groups)
print(pattern.search("balloon", 4).group(), pattern.match("llama").span(), pattern.match("balloon"), pattern.fullmatch("ll").group())
print(repr(pattern), dict(re.compile(r"(?P<a>x)(?P<b>y)").groupindex))
print(bool(re.search(r"^\s*$", "   ")), bool(re.search(r"^\s*$", " x ")))
print(re.search(r"colou?r", "the color red").group(), re.search(r"gr[ae]y", "grey").group())
print(re.findall(r"\b\w{5}\b", "three words apart, hello again"))
print(re.findall(r"[^aeiou\s]+", "regular expressions"))
print(re.findall(r"\d+\.\d+|\d+", "3.14 and 42 and .5"))
print(re.findall(r"a{2,3}", "a aa aaa aaaa"), re.findall(r"a{,2}b", "b ab aab aaab"), re.findall(r"ab*?", "abbb"), re.findall(r"<.+?>", "<a><b>"))
print(re.search(r"end$", "the end\n") is not None, re.search(r"end\Z", "the end\n"), re.search(r"\Athe", "the end") is not None)
print(re.findall(r"^\w+", "one two\nthree four"), re.findall(r"^\w+", "one two\nthree four", re.MULTILINE), re.findall(r"\w+$", "one two\nthree four", re.M))
print(re.findall(r"a.c", "abc a\nc"), re.findall(r"a.c", "abc a\nc", re.DOTALL), re.findall(r"(?i)pip", "Pip PIP pip"))
print(re.search(r"(?=.*\d)(?=.*[a-z])\w+", "abc123").group(), re.findall(r"\w+(?=!)", "hey! you there!"))
print(re.findall(r"(?<=#)\w+", "#tag and #more"), re.findall(r"\b(?!the\b)\w+", "the cat the hat"))
print(re.findall(r"[\w.]+@[\w.]+", "mail ada@tower.org or pip@deck.net now"), re.findall(r"[]x]+", "a]x]b"), re.findall(r"[a\-z]+", "a-z b"))
print(re.findall(r"(?:ab)+", "ababab ab"), re.findall(r"(ab)+", "ababab ab"), re.findall(r"(a)|(b)", "ab"))
print(re.search(r"(\d+)\s*(?#the unit)(kg|m)", "load 12 kg").groups(), re.match(r"\s*", "   x").end(), re.search(r"x*", "aaa").span())
