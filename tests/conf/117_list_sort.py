# Sorting: list.sort and sorted, key functions, reverse, stability
nums = [5, 2, 9, 1, 5, 6]
print("sorted:", sorted(nums), "original:", nums)
nums.sort()
print("sort in place:", nums)
nums.sort(reverse=True)
print("reverse:", nums)
print("sorted reverse:", sorted([3, 1, 2], reverse=True))
print("strings:", sorted(["pear", "Apple", "fig", "apple"]))
print("case-insensitive:", sorted(["pear", "Apple", "fig", "apple"], key=lambda s: s.lower()))
print("by length:", sorted(["ccc", "a", "bb", "dd"], key=len))
print("by length desc:", sorted(["ccc", "a", "bb", "dd"], key=len, reverse=True))
print("floats/negatives:", sorted([2.5, -1, 0, 3, -2.5]))
print("by abs:", sorted([-3, 1, -2, 2], key=abs))
print("tuples:", sorted([(2, "b"), (1, "z"), (2, "a"), (1, "a")]))
print("by second:", sorted([(2, "b"), (1, "z"), (3, "a")], key=lambda t: t[1]))
print("chars:", sorted("python"), "".join(sorted("python", reverse=True)))
print("sorted of dict gives keys:", sorted({"b": 1, "a": 2}))
print("dict by value:", sorted({"x": 3, "y": 1, "z": 2}.items(), key=lambda kv: kv[1]))
print("set/tuple/range:", sorted({3, 1, 2}), sorted((3, 1)), sorted(range(3, 0, -1)))
print("empty/single:", sorted([]), sorted([7]))
print("lists of lists:", sorted([[2, 1], [1, 5], [1, 2]]))

people = [("ann", 30), ("bob", 25), ("cy", 30), ("dee", 25), ("eve", 35)]
print("stable by age:", sorted(people, key=lambda p: p[1]))
print("reverse keeps tie order:", sorted(people, key=lambda p: p[1], reverse=True))
print("age desc then name:", sorted(people, key=lambda p: (-p[1], p[0])))
two_pass = sorted(people, key=lambda p: p[0], reverse=True)
two_pass.sort(key=lambda p: p[1])
print("two-pass sort:", two_pass)
words = ["banana", "kiwi", "apple", "fig", "cherry"]
print("by last letter:", sorted(words, key=lambda w: w[-1]))
print("by (len, alpha):", sorted(words, key=lambda w: (len(w), w)))
print("min/max with key:", min(words, key=len), max(words, key=len))
records = [{"n": "b", "v": 2}, {"n": "a", "v": 2}, {"n": "c", "v": 1}]
records.sort(key=lambda r: r["v"])
print("dicts by field:", [r["n"] for r in records])

def by_digit_sum(n):
    return sum(int(d) for d in str(n))

print("named key function:", sorted([19, 100, 23, 8], key=by_digit_sum))
print("numeric strings:", sorted(["10", "9", "100"]), sorted(["10", "9", "100"], key=int))
print("sort returns None:", [2, 1].sort())
ordered = sorted(nums)
print("sorted makes a new list:", ordered is nums, ordered == sorted(nums))
print("reversed vs sorted reverse:", list(reversed([1, 3, 2])), sorted([1, 3, 2], reverse=True))
print("top 3:", sorted([4, 9, 1, 7, 3], reverse=True)[:3])
print("median:", sorted([7, 1, 5])[1])
print("is sorted:", nums == sorted(nums), [1, 2, 2] == sorted([1, 2, 2]))
print("anagrams:", sorted("listen") == sorted("silent"))
print("unique sorted:", sorted(set([3, 1, 3, 2, 1])))
print("sort by key with ties:", sorted(["bb", "a", "cc", "d"], key=len))
print("descending strings:", sorted(["b", "c", "a"], reverse=True))
print("method as key:", sorted(["pear", "Apple", "fig"], key=str.lower))
