# int: arbitrary size, division and modulo rules, conversions
import math

print("2**100:", 2 ** 100)
print("2**64:", 2 ** 64)
print("factorial(30):", math.factorial(30))
print("big product:", 99999999999 * 99999999999)
print("big sum:", 2 ** 70 + 1)
print("big negative:", -(10 ** 25))
print("big floor div:", 10 ** 30 // 7)
print("big mod:", 10 ** 30 % 7)
print("big compare:", 2 ** 100 > 10 ** 30, 2 ** 100 == 1267650600228229401496703205376)
print("big digit count:", len(str(2 ** 200)))
print("64-bit boundary:", 2 ** 63 - 1, 2 ** 63, -(2 ** 63) - 1)
print("exact big division:", 10 ** 20 // 10 ** 10, 10 ** 20 % (10 ** 10 + 1))
print("sum of big:", sum([10 ** 20, 10 ** 20, 1]))
n = 10 ** 18
n += 1
print("augmented big:", n)
print("big subtraction:", 2 ** 100 - 2 ** 99, 10 ** 20 - 1)
print("big negative floor div:", -(10 ** 20) // 3, -(10 ** 20) % 3)
print("big square:", 12345678901234567890 ** 2)

print("underscores:", 1_000_000, 1_0, 12_345.5)
print("floor div:", 7 // 2, -7 // 2, 7 // -2, -7 // -2)
print("modulo:", 7 % 3, -7 % 3, 7 % -3, -7 % -3)
print("divmod:", divmod(7, 2), divmod(-7, 2), divmod(7, -2))
print("true division gives float:", 6 / 2, 7 / 2, -1 / 4)
print("power:", 3 ** 4, 2 ** 0, (-3) ** 3, 10 ** 3)
print("negative power gives float:", 2 ** -2, 10 ** -1)
print("pow 3 args:", pow(2, 10, 1000), pow(3, 200, 13))
print("abs:", abs(-5), abs(5), abs(-2 ** 70))

print("int from str:", int("42"), int("-17"), int("  8  "), int("+5"))
print("int from float truncates:", int(3.9), int(-3.9), int(2.0))
print("int from bool:", int(True), int(False))
print("int with base:", int("ff", 16), int("101", 2), int("777", 8))
print("int default:", int())
print("str of int:", str(123) + "4", str(-5))
print("float of int:", float(3))
print("even/odd:", 10 % 2 == 0, 7 % 2 == 1)
print("digit sum:", sum(int(ch) for ch in str(2 ** 50)))
print("last digit:", 12345 % 10, "without last:", 12345 // 10)
print("reverse digits:", int(str(12345)[::-1]))
print("int equals float:", 3 == 3.0, 10 ** 2 == 100.0)
print("comparison:", 5 > 3, -1 < 0, 2 <= 2)
print("types:", type(5).__name__, type(2 ** 100).__name__, type(5 // 2).__name__)
print("isinstance:", isinstance(5, int), isinstance(5.0, int), isinstance(True, int))
print("big int to float:", float(10 ** 20), 10 ** 20 / 10 ** 18)
print("big equals float:", 10 ** 15 == 1e15)
