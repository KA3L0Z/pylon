# print(): separators, end, *args and how values are displayed
print("hello")
print()
print("a", "b", "c")
print("a", "b", "c", sep="")
print("a", "b", "c", sep="-")
print("a", "b", "c", sep=", ")
print("no newline", end="")
print(" <- same line")
print("custom end", end="!\n")
print("one", "two", sep=" | ", end=" END\n")
print(1, 2.5, True, None)
print("int:", 42)
print("negative:", -7)
print("float:", 3.0)
print("bools:", True, False)
print("none:", None)
print("str:", "plain text")
print("list of str:", ["a", "b"])
print("mixed list:", [1, "two", 3.0, None, True])
print("tuples:", (1, 2), (1,), ())
print("dict:", {"k": 1, "n": [1, 2]})
print("nested:", [[1, 2], (3, "x")], {"t": (1, "a")})
print("empties:", [], {}, ())

nums = [1, 2, 3]
print(*nums)
print(*nums, sep=", ")
print("values:", *nums, "done")
print(*"abc", sep="/")
print(*[], "after empty unpack")
print("multi\nline")
print("tab\tseparated")
print("")
print("a" + "b", "c" * 3)
print("expr:", 2 + 3, 10 / 4, 7 // 2)

for i in range(3):
    print(i, end=" ")
print("|")
for word in ["x", "y", "z"]:
    print(word, end="")
print()
print("first", end=", ")
print("second", end=", ")
print("third")
print("sep only matters between args", sep="***")
print(1, 2, 3, sep="\n")
